// Renders the Homebrew formula for a published version of this package.
//
// The formula is generated rather than committed because Homebrew wants the
// sha256 of the exact file it will download, and npm only advertises a sha512
// integrity string — so the tarball has to be fetched and hashed, not described.
// Doing that here instead of by hand at release time is what keeps the tap from
// ever pointing at the wrong bytes.
//
// The rendered formula lives in the tap repository (meyusufdemirci/homebrew-tap);
// this repository holds only the generator, so there is one source of truth and
// nothing in-tree to go stale between releases.
//
//   node scripts/formula.mjs                        # this package.json's version, to stdout
//   node scripts/formula.mjs --version latest       # whatever npm currently serves
//   node scripts/formula.mjs --version 0.3.0 --out Formula/claude-code-session-tracker.rb
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const REGISTRY = 'https://registry.npmjs.org';

// A version published seconds ago is not always resolvable on the first try, and
// the release job runs immediately after `npm publish`. Waiting beats failing a
// release over CDN propagation.
const MANIFEST_ATTEMPTS = 12;
const MANIFEST_RETRY_MS = 10_000;

function flag(name, fallback = undefined) {
  const index = process.argv.indexOf(`--${name}`);
  if (index === -1) return fallback;
  const value = process.argv[index + 1];
  if (value === undefined || value.startsWith('--')) throw new Error(`--${name} needs a value`);
  return value;
}

const sleep = (ms) => new Promise((done) => setTimeout(done, ms));

/** Homebrew derives the class name from the file name; this is the same rule. */
function className(packageName) {
  return packageName.split(/[-_]/).map((part) => part[0].toUpperCase() + part.slice(1)).join('');
}

/** `brew audit` rejects a trailing period, and a URL fragment is noise in `homepage`. */
const asDesc = (value) => value.trim().replace(/\.$/, '');
const asHomepage = (value) => value.split('#')[0];

async function manifest(name, version) {
  const url = `${REGISTRY}/${encodeURIComponent(name)}/${version}`;
  for (let attempt = 1; ; attempt += 1) {
    const response = await fetch(url);
    if (response.ok) return response.json();
    if (response.status !== 404 || attempt === MANIFEST_ATTEMPTS) {
      throw new Error(`${name}@${version} is not on the registry (HTTP ${response.status})`);
    }
    console.error(`  ${name}@${version} not resolvable yet, retrying (${attempt}/${MANIFEST_ATTEMPTS - 1})`);
    await sleep(MANIFEST_RETRY_MS);
  }
}

async function sha256(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`GET ${url} failed with HTTP ${response.status}`);
  return createHash('sha256').update(Buffer.from(await response.arrayBuffer())).digest('hex');
}

function render({ name, version, tarball, checksum, desc, homepage, license }) {
  return `# Generated by scripts/formula.mjs in ${homepage.replace('https://github.com/', '')}.
# Edits here are overwritten by the next release — change the generator instead.
class ${className(name)} < Formula
  desc "${desc}"
  homepage "${homepage}"
  url "${tarball}"
  sha256 "${checksum}"
  license "${license}"

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink Dir["#{libexec}/bin/*"]
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/${name} --version")

    # A machine that has never run Claude Code is the state every install starts
    # in, and the answer to it is an empty list rather than an error.
    result = JSON.parse(shell_output("#{bin}/${name} --json --claude-dir #{testpath}/claude"))
    assert_equal 0, result["total"]
    assert_empty result["sessions"]
  end
end
`;
}

const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'));
const requested = flag('version', pkg.version);
const out = flag('out');

const meta = await manifest(pkg.name, requested);
const tarball = meta.dist?.tarball;
if (!tarball) throw new Error(`${pkg.name}@${meta.version} has no tarball on the registry`);

const formula = render({
  name: pkg.name,
  version: meta.version,
  tarball,
  checksum: await sha256(tarball),
  desc: asDesc(pkg.description),
  homepage: asHomepage(pkg.homepage),
  license: pkg.license,
});

if (out) {
  const path = resolve(out);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, formula);
  console.error(`  wrote ${pkg.name}@${meta.version} to ${path}`);
} else {
  process.stdout.write(formula);
}
